export const STRINGS: Record<UiLang, Record<UiKey, string>> = { en, de, vi };

export const UiLangContext = createContext<{
  lang: UiLang;
  setLang: (lang: UiLang) => void;
}>({ lang: "en", setLang: () => {} });

/**
 * Returns a translator for the active interface language. Placeholders are
 * `{name}` and substituted from the second argument.
 */
export function useUi() {
  const { lang, setLang } = useContext(UiLangContext);
  // Memoised on the language alone. Callers put t in their dependency arrays,
  // so a fresh function on every render would re-fire their effects endlessly.
  const t = useCallback(
    (key: UiKey, vars?: Record<string, string | number>): string => {
      let value: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(replacement));
        }
      }
      return value;
    },
    [lang],
  );
  return { t, lang, setLang };
}

